#!/usr/bin/env python3
"""
Generate a weak-scaling case of the f3p (three-point bending) test: a beam made of N copies, along
its width (y), of a Neper sample periodic in y.

    python3 make_f3p_weak_scaling.py N [--out case_yN] [--steps 30000] [--cell-size 0.2]

Creates <out>/ with:
    beam.conf            N*1000 fragments (all in cluster 0 -> copies glued by apply_particle_sticking)
    beam_pery.shp        shapes (same 1000 shapes whatever N)
    support_left.shp, support_right.shp, punch.shp   cylinders spanning the whole width
    f3p.msp              input deck, domain sized for N (cell_size chosen for MPI decomposition)
Run:  cd <out> && mpirun -n P exaDEM f3p.msp --nogpu

Sample (beam_pery.shp / beam_pery_sticked.conf next to this script), Neper 7, regular (centroidal)
cells to avoid tiny fragments, periodic along y so that copies tile seamlessly:
    neper -T -n 1000 -id 2 -domain "cube(2,0.5,0.5)" -periodicity y -morpho centroidal \
          -transform "translate(-1,-0.25,-0.25)" -o beam_pery
    cd <exaDEM>/scripts && PYTHONPATH=. python3 pre_processing/tess2rockable.py beam_pery.tess 1e-3 beam_pery.shp
(then set "shapeFile beam_pery.shp" in beam_pery_sticked.conf).
Note: tess2rockable puts the fragments in group 1.

Work per copy is constant: N copies <-> N times more particles, domain grows along y only.
"""
import argparse
import math
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
# exaDEM python scripts: $EXADEM_SCRIPTS or <exaDEM sources>/scripts (this file is in example/polyhedra/f3p/weak_scaling)
SCRIPTS = os.environ.get("EXADEM_SCRIPTS", os.path.normpath(os.path.join(HERE, "..", "..", "..", "..", "scripts")))
if not os.path.isfile(os.path.join(SCRIPTS, "pre_processing", "replicate_periodic.py")):
    sys.exit(f"exaDEM scripts not found in {SCRIPTS}: set EXADEM_SCRIPTS=<exaDEM sources>/scripts")
sys.path.insert(0, SCRIPTS)
sys.path.insert(0, os.path.join(SCRIPTS, "pre_processing"))
from lib.io_utils import read_rockable_file, write_rockable_file  # noqa: E402
from replicate_periodic import replicate  # noqa: E402

PERIOD = [0.0, 0.5, 0.0]  # the sample is periodic along y with period 0.5 (Neper -periodicity y)
CONF = os.path.join(HERE, "beam_pery_sticked.conf")
SHP = os.path.join(HERE, "beam_pery.shp")
OVERHANG = 0.10   # cells of a periodic tessellation stick out of the domain (max ~0.07 here)
R_MAX = 0.0829    # max bounding radius of the fragments

CYLINDER = """<
name {name}
radius 0.01
preCompDone y
nv 2
0 {ym} 0
0 {yp} 0
ne 1
0 1
nf 0
obb.extent 0.01 {ext} 0.01
obb.e1 1 0 0
obb.e2 0 1 0
obb.e3 0 0 1
obb.center 0 0 0
volume 0.008578642339403
I/m 0.00493333 0.00493333 0.0032
>
"""

MSP = """# f3p weak scaling: three-point bending of a beam made of {n} copies (along y) of a Neper sample
# periodic in y ([-1,1]x[-0.25,0.25]x[-0.25,0.25], 1000 centroidal cells, minkowski 1e-3).
# Generated by make_f3p_weak_scaling.py.
# Beam: [-1,1] x [{y0:g},{y1:g}] x [-0.25,0.25], {npart} fragments.
# Note: 1000 different shapes -> exaNBody must be built with -DXNB_PARTICLE_TYPE_INT=uint16_t.

includes:
  - config_fragmentation.msp

io_tree:
  - io_config:
     dir_name: "F3P_WS_Y{n}"

input_data:
  - read_conf_rockable:
     filename: beam.conf
     bounds_mode: DOMAIN
  - density_from_shape:
     density: 0.006
  - inertia_from_shape
  - set_velocity:
     value: [0, 0, 0]
  - multimat_contact_params:
     default_config: {{ dncut: 0, kn: 1e4, kt: 8e3, kr: 0.0, fc: 0.0, mu: 0.3, damp_rate: 0.83}}
  - drivers_contact_params:
     default_config: {{ dncut: 0, kn: 1e4, kt: 8e3, kr: 0.0, fc: 0.0, mu: 0.3, damp_rate: 0.83}}
  - inner_bond_params:
     default_config: {{ kn: 2.e3, kt: 16.e2, damp_rate: 0.83, g: 2.e-1 }}

compute_force:
  - gravity_force:
     gravity: [0,0,0]
  - contact_multimat_polyhedron
  - inner_bond_polyhedron

setup_drivers:
  - register_rshape:
     id: 0
     state: {{center: [0.9,0,-0.261]}}
     params:
        motion_type: STATIONARY
     filename: support_right.shp
     minkowski: 0.001 m
  - register_rshape:
     id: 1
     state: {{center: [-0.9,0,-0.261]}}
     params:
        motion_type: STATIONARY
     filename: support_left.shp
     minkowski: 0.001 m
  - register_rshape:
     id: 2
     state: {{center: [0.,0,0.261]}}
     params: {{ motion_type: LINEAR_MOTION, motion_vector: [0,0,-1], const_vel: 5.0 }}
     filename: punch.shp
     minkowski: 0.001 m

domain:
  cell_size: {cs:g} m
  periodic: [false, false, false]
  grid_dims: [{gx}, {gy}, {gz}]
  bounds: [[{bx0:g} m, {by0:g} m, {bz0:g} m], [{bx1:g} m, {by1:g} m, {bz1:g} m]]
  expandable: true

global_stress_tensor:
  - avg_stress_tensor:
     volume : 1

global:
  simulation_dump_frequency: -1
  analysis_interaction_dump_frequency: -1
  simulation_end_iteration: {steps}
  simulation_log_frequency: 100
  simulation_paraview_frequency: {pvfreq}
  analysis_dump_stress_tensor_frequency: 1000
  apply_particle_sticking: true
  sticking_threshold: 1e-3
  rcut_inc: 0.01
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("n", type=int, help="number of copies along the width (y)")
    ap.add_argument("--out", help="output directory (default: ./case_y<N>)")
    ap.add_argument("--steps", type=int, default=30000)
    ap.add_argument("--paraview", type=int, default=-1, help="paraview output frequency (-1: none)")
    ap.add_argument("--cell-size", type=float, default=0.2)
    args = ap.parse_args()

    n, cs = args.n, args.cell_size
    if cs < 2 * R_MAX + 0.01:
        ap.error(f"cell size must be >= {2 * R_MAX + 0.01:.3f}")
    out = args.out or f"case_y{n}"
    os.makedirs(out, exist_ok=True)

    period = PERIOD
    data = replicate(read_rockable_file(CONF), [1, n, 1], period, center=True)
    data.params.values["shapeFile"] = "beam_pery.shp"
    write_rockable_file(os.path.join(out, "beam.conf"), data)
    shutil.copy(SHP, os.path.join(out, "beam_pery.shp"))

    half_w = n * period[1] / 2.0
    y_cyl = half_w + OVERHANG + 0.05
    for name in ("support_left", "support_right", "punch"):
        with open(os.path.join(out, f"{name}.shp"), "w") as f:
            f.write(CYLINDER.format(name=name, ym=-y_cyl, yp=y_cyl, ext=y_cyl))

    def cells(half):  # number of cells covering [-half, half]
        return 2 * math.ceil(half / cs)
    gx, gy, gz = cells(1.0 + OVERHANG + cs / 2), cells(y_cyl + cs / 2), cells(0.25 + 0.05 + cs / 2)
    with open(os.path.join(out, "f3p.msp"), "w") as f:
        f.write(MSP.format(n=n, y0=-half_w, y1=half_w, npart=data.n_particles, cs=cs, gx=gx, gy=gy, gz=gz,
                           bx0=-gx * cs / 2, bx1=gx * cs / 2, by0=-gy * cs / 2, by1=gy * cs / 2,
                           bz0=-gz * cs / 2, bz1=gz * cs / 2, steps=args.steps, pvfreq=args.paraview))
    print(f"{out}: {data.n_particles} particles, grid {gx}x{gy}x{gz} (cell {cs}), cylinders y in +/-{y_cyl:g}")


if __name__ == "__main__":
    main()
